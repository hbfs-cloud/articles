#!/usr/bin/env node
'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { calendarForSymbol, nextSession, isSession } = require('./lib/equity-session-calendars');
const { fetchCertifiedDailyBars, normalizeBars } = require('./lib/mcp-daily-bars');
const E = 'euronext_cash_2025_2026';
assert.equal(calendarForSymbol('KBC.BR'), E);
assert.equal(calendarForSymbol('EDP.LS'), E);
assert.equal(calendarForSymbol('AMP.MI'), 'borsa_italiana_cash_2025_2026');
assert.equal(calendarForSymbol('ITX.MC'), 'bme_cash_2025_2026');
assert.equal(calendarForSymbol('PGE.WA'), 'gpw_cash_2025_2026');
assert.equal(calendarForSymbol('GLEN.L'), 'lse_cash_2025_2026');
assert.equal(calendarForSymbol('SAP.DE'), 'xetra_cash_2025_2026');
assert.equal(calendarForSymbol('NOKIA.HE'), 'nasdaq_helsinki_cash_2025_2026');
assert.equal(nextSession('2025-04-17', E), '2025-04-22');
assert.equal(nextSession('2025-08-14', 'borsa_italiana_cash_2025_2026'), '2025-08-18');
assert.equal(nextSession('2025-06-18', 'gpw_cash_2025_2026'), '2025-06-20');
assert.equal(nextSession('2025-08-22', 'lse_cash_2025_2026'), '2025-08-26');
assert.equal(nextSession('2025-12-23', 'bme_cash_2025_2026'), '2025-12-24');
assert.equal(nextSession('2026-06-03', 'gpw_cash_2025_2026'), '2026-06-05');
assert.equal(nextSession('2026-11-10', 'gpw_cash_2025_2026'), '2026-11-12');
assert.equal(nextSession('2026-07-02', E), '2026-07-03');
assert.equal(nextSession('2026-09-04', E), '2026-09-07');
assert.equal(nextSession('2026-04-02', E), '2026-04-07');
assert.equal(nextSession('2026-12-23', E), '2026-12-24');
assert.equal(nextSession('2026-12-23', 'borsa_italiana_cash_2025_2026'), '2026-12-28');
assert.equal(nextSession('2026-08-28', 'lse_cash_2025_2026'), '2026-09-01');
assert.equal(nextSession('2026-12-24', 'lse_cash_2025_2026'), '2026-12-29');
assert.equal(nextSession('2025-12-29', 'xetra_cash_2025_2026'), '2025-12-30');
assert.equal(nextSession('2025-12-30', 'xetra_cash_2025_2026'), '2026-01-02');
assert.equal(nextSession('2025-06-19', 'nasdaq_helsinki_cash_2025_2026'), '2025-06-23');
assert.equal(nextSession('2026-05-13', 'nasdaq_helsinki_cash_2025_2026'), '2026-05-15');
assert.equal(isSession('2026-12-24', E), true); // Lisbon is an Euronext half-day, not a closure.
assert.equal(isSession('2026-12-24', 'lse_cash_2025_2026'), true);
assert.equal(isSession('2025-12-30', 'xetra_cash_2025_2026'), true);
assert.equal(isSession('2026-05-14', 'nasdaq_helsinki_cash_2025_2026'), false);
assert.throws(() => isSession('2024-12-31', E), /no certified calendar/);
assert.throws(() => isSession('2027-01-04', E), /no certified calendar/);
assert.throws(() => isSession('2027-01-04', 'lse_cash_2025_2026'), /no certified calendar/);
assert.throws(() => isSession('2027-01-04', 'xetra_cash_2025_2026'), /no certified calendar/);
const rows = dates => dates.map(date => [date,10,12,9,11,100]);
assert.doesNotThrow(() => normalizeBars({bars: rows(['2025-04-17','2025-04-22','2025-04-23'])}, 'KBC.BR', E));
assert.doesNotThrow(() => normalizeBars({bars: rows(['2026-07-02','2026-07-03','2026-07-06'])}, 'KBC.BR', E));
assert.doesNotThrow(() => normalizeBars({bars: rows(['2026-08-28','2026-09-01'])}, 'GLEN.L', 'lse_cash_2025_2026'));
assert.doesNotThrow(() => normalizeBars({bars: rows(['2026-04-02','2026-04-07'])}, 'SAP.DE', 'xetra_cash_2025_2026'));
assert.doesNotThrow(() => normalizeBars({bars: rows(['2026-05-13','2026-05-15'])}, 'NOKIA.HE', 'nasdaq_helsinki_cash_2025_2026'));
assert.throws(() => normalizeBars({bars: rows(['2026-07-02','2026-07-06'])}, 'KBC.BR', E), /incomplete/);
assert.throws(() => normalizeBars({bars: rows(['2026-08-28','2026-09-02'])}, 'GLEN.L', 'lse_cash_2025_2026'), /incomplete/);
assert.throws(() => normalizeBars({bars: rows(['2026-04-03'])}, 'KBC.BR', E), /non-session/);
assert.throws(() => normalizeBars({bars: rows(['2026-04-02','2026-04-06','2026-04-07'])}, 'SAP.DE', 'xetra_cash_2025_2026'), /non-session/);
assert.throws(() => normalizeBars({bars: rows(['2026-05-13','2026-05-14','2026-05-15'])}, 'NOKIA.HE', 'nasdaq_helsinki_cash_2025_2026'), /non-session/);
const status = {server_version:'test-new-build',operation_readiness:{bars_daily_us_equity:{status:'ready',asset_calendar:'us_equity_exchange_sessions',expected_completed_end:'2026-09-11',served_completed_end:'2026-09-11'}}};
const response = (symbol, calendar, cellStatus='completed') => ({results:[{cells:[{symbol,status:cellStatus,asset_calendar:calendar,expected_completed_end:'2026-09-11',served_completed_end:'2026-09-11',retry_at:'2026-09-12T20:00:00Z'}],data:[{symbol,asset_calendar:calendar,expected_completed_end:'2026-09-11',served_completed_end:'2026-09-11',bars:rows(['2026-09-10','2026-09-11'])}]}]});
async function main() {
 const calls=[];
 const client={canCallDirectly:()=>true,callToolWithRetry:async(_s,tool,args)=>{calls.push({tool,args});return tool==='GetStatus'?status:response(args.symbols,calendarForSymbol(args.symbols));}};
 const result=await fetchCertifiedDailyBars({symbols:['AAPL','TTE.PA','KBC.BR','EDP.LS','AMP.MI','GLEN.L','SAP.DE','NOKIA.HE'],refdate:'2026-09-11',asOfTimestamp:'2026-09-12T19:00:00Z',batchSize:1,client,receiptDir:null});
 assert.equal(result.size,8);
 assert.equal(calls.filter(x=>x.tool==='QueryData').length,8);
 const wrong={...client,callToolWithRetry:async(_s,tool)=>tool==='GetStatus'?status:response('KBC.BR','us_equity_exchange_sessions')};
 await assert.rejects(()=>fetchCertifiedDailyBars({symbols:['KBC.BR'],refdate:'2026-09-11',asOfTimestamp:'2026-09-12T19:00:00Z',client:wrong,receiptDir:null}),/asset_calendar mismatch/);
 const receiptDir=fs.mkdtempSync(path.join(os.tmpdir(),'tracking-calendar-test-'));
 const pollIds=[];
 const partial={...client,callToolWithRetry:async(_s,tool)=>tool==='GetStatus'?status:{job_id:'same-job',status:'queued'},awaitJob:async(_s,id)=>{pollIds.push(id);return response('TTE.PA',E,'partial');}};
 await assert.rejects(()=>fetchCertifiedDailyBars({symbols:['TTE.PA'],refdate:'2026-09-11',asOfTimestamp:'2026-09-12T19:00:00Z',client:partial,receiptDir}),/partial.*retry_at=2026-09-12T20:00:00Z/);
 assert.deepEqual(pollIds,['same-job']);
 const receipts=fs.readdirSync(receiptDir).map(file=>JSON.parse(fs.readFileSync(path.join(receiptDir,file))));
 assert.equal(receipts.length,2);
 assert(receipts.every(r=>r.job_id==='same-job'));
 assert(receipts.some(r=>r.phase==='terminal' && r.response.results[0].cells[0].retry_at==='2026-09-12T20:00:00Z'));
 console.log('EU tracking calendars and failed response receipts: PASS');
}
main().catch(e=>{console.error(e);process.exit(1)});

'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { render, validate, SCHEMA } = require('./render-analysis');
const data = JSON.parse(fs.readFileSync(path.join(__dirname, '../data/analyses-data/TSM.json'), 'utf8'));
data.social = { platforms: [] };
data.fundamentals.rows[0].note = 'The denominator covers four reported quarters.';
data.fundamentals.rows[0].comparison = 'Historical comparison uses the same denominator.';
data.risks.riskCards = [{ title: 'Qualitative risk', severity: 'high', points: ['Evidence is qualitative.'], impact: 'Structural' }];
let html = render(data);
assert(html.includes(data.fundamentals.rows[0].note) && html.includes(data.fundamentals.rows[0].comparison), 'valuation qualifications and comparisons must be visible to readers');
assert(html.includes('<table class="coverage-matrix">'), 'legacy coverage table must render as a table');
data.business.coverageMatrix = [{ facet: '<script>bad</script>', status: 'Partiel', decision: 'No directional inference' }];
html = render(data);
assert(html.includes('&lt;script&gt;bad&lt;/script&gt;'), 'structured coverage text must remain escaped');
assert(!html.includes('<script>bad</script>'), 'coverage rendering must not allow markup injection');
const schemaData = JSON.parse(JSON.stringify(data));
delete schemaData.risks.riskCards[0].impact; // legacy prose is renderable but not a valid new quantitative field
assert.deepEqual(validate(schemaData, SCHEMA), [], 'rendered notes and coverage rows must also satisfy the strict schema');
const invalidRisk = JSON.parse(JSON.stringify(schemaData));
invalidRisk.risks.riskScore = 62;
assert(validate(invalidRisk, SCHEMA).some(e => e.includes('riskScore')), 'risk remains an integer on the established 1–10 scale');
assert(!html.includes('href="#social"'), 'empty social section must not leave a dead navigation link');
data.social.platforms = [{ platform: 'Sentiment', mentions: 'N/D — facette indisponible', trend: 'indisponible' }];
assert(!render(data).includes('id="social"'), 'an explicit unavailable placeholder belongs in coverage, not a large social card');
data.social.platforms = [{ platform: 'Forum', mentions: '0 mentions', trend: 'neutral' }];
assert(render(data).includes('id="social"'), 'a genuine zero observation is not missing data');
assert(!html.includes('class="risk-meters"'), 'missing or qualitative values must not manufacture quantitative meters');
assert(!html.includes('<th>Corr. hors QQQ</th>') && !html.includes('<th>Bêta résiduel</th>'), 'generic table must not claim residualization');
data.risks.riskCards[0].probability = 0;
data.risks.riskCards[0].impact = 150;
html = render(data);
assert(html.includes('risk-meter-fill" style="width:0%;'), 'a provided zero must be retained');
assert(html.includes('risk-meter-fill" style="width:100%;'), 'provided values remain bounded');
data.risks.riskCards[0].probability = '25%';
data.risks.riskCards[0].impact = '50 companies';
html = render(data);
assert(html.includes('risk-meter-fill" style="width:25%;'), 'legacy numeric percentage remains supported');
assert.equal((html.match(/class="risk-meter-fill"/g) || []).length, 1, 'numeric-looking prose is not a measured value');
const windowData = JSON.parse(JSON.stringify(schemaData));
windowData.performance = { windowReturns: {
  label: 'Twenty-one sessions <price only>', startDate: '2026-08-19', endDate: '2026-09-18',
  rows: [{ ticker: 'KLAC', returnPct: -5.49 }, { ticker: 'SMH', returnPct: 2.34 }],
} };
assert.deepEqual(validate(windowData, SCHEMA), []);
const windowHtml = render(windowData).split('id="performance"')[1].split('</table>')[0];
assert(windowHtml.includes('Twenty-one sessions &lt;price only&gt;'));
assert(windowHtml.includes('2026-08-19') && windowHtml.includes('-5.49 %') && windowHtml.includes('+2.34 %'));
assert(!windowHtml.includes('YTD') && !windowHtml.includes('Alpha'), 'finite-window returns must not be labelled YTD or alpha');
windowData.performance.windowReturns.rows[0].returnPct = 'not measured';
assert(validate(windowData, SCHEMA).some(error => error.includes('returnPct')));
windowData.performance = { benchmarks: [{ name: 'S&P 500', ticker: 'SPY', ytd: '+8.2%' }] };
assert(render(windowData).includes('<th>YTD</th>'), 'legacy YTD benchmarks retain their existing meaning');
const draft = JSON.parse(JSON.stringify(schemaData));
draft.meta.lang = 'fr';
draft.meta.status = 'no-trade';
draft.tradeIdea.status = 'no-trade';
draft.tradeIdea.statusNote = 'Repères conservés sans réactivation.';
draft.verdict.controlChecklist = [{ label: 'Calendrier', status: 'unknown', statusLabel: 'À confirmer', evidence: 'Date non confirmée.', action: 'Vérifier.' }];
draft.earnings = { quarters: [], beatNote: 'La période fiscale reste à réconcilier.', nextEarnings: 'Non confirmée' };
draft.business.segments = [{ name: 'Activité', description: 'Description sans chiffres.' }];
draft.insiders = { signal: 'Historique partiel.' };
draft.shortInterest = { trend: 'Base à réconcilier.' };
draft.options = { unusual: 'Aucune interprétation directionnelle.' };
draft.capitalFlow = { netFlow: 'N/A', institutionalFlow: 'N/A', retailFlow: 'N/A', signal: 'Absence de flux signé.' };
const draftHtml = render(draft);
assert(draftHtml.includes('AUCUN ORDRE ACTIF') && draftHtml.includes('Repères historiques du trade'));
assert(draftHtml.includes(draft.tradeIdea.statusNote) && draftHtml.includes('Ancien stop'));
assert(!draftHtml.includes('aucun achat avant les résultats'), 'a checklist cannot invent an earnings condition');
assert(!draftHtml.includes('Snapshot avant résultats'), 'an options section cannot invent event timing');
assert(draftHtml.includes('id="earnings"') && draftHtml.includes('href="#earnings"') && draftHtml.includes(draft.earnings.beatNote));
assert(!draftHtml.split('id="earnings"')[1].split('id="insiders"')[0].includes('<table'), 'narrative-only earnings must not create an empty table');
const segments = draftHtml.split('<h4 style="margin-top:1rem;">Segments</h4>')[1].split('</table>')[0];
assert(!segments.includes('Revenus'), 'segment revenue column requires actual data');
for (const id of ['insiders', 'short', 'options', 'capitalflow']) {
  const section = draftHtml.split(`id="${id}"`)[1].split('class="content-card"')[0];
  assert(!section.includes('tm-value') && !section.includes('metric-strip'), `${id}: missing observations must not create empty metric tiles`);
}
draft.insiders.insiderPct = '0%';
draft.shortInterest.daysToCover = '0';
draft.options.callOI = '0';
draft.capitalFlow.netFlow = '0';
assert.equal((render(draft).match(/class="tm-value">0(?:%)?<\/div>/g) || []).length, 4, 'measured zeros survive all sparse metric sections');
draft.earnings = { quarters: [] };
assert(!render(draft).includes('href="#earnings"'), 'truly empty earnings has no navigation target');
draft.earnings = { quarters: [], beatNote: 'Période non confirmée.' };
assert(render(draft).includes('Résultats et calendrier'));
draft.verdict.controlChecklist = [];
draft.tradeIdea.status = 'active';
const conservativeHtml = render(draft);
assert(conservativeHtml.split('id="verdict"')[1].split('id="business"')[0].includes('AUCUN ORDRE ACTIF'));
assert(conservativeHtml.split('id="trade"')[1].includes('Repères historiques du trade'), 'meta no-trade conservatively overrides inconsistent active trade status');
windowData.performance = { ytd: '8.2%', alpha: '4%', windowReturns: { label: 'Specific period', startDate: '2026-08-19', endDate: '2026-09-18', rows: [{ ticker: 'KLAC', returnPct: 0 }] } };
const mixedPeriodHtml = render(windowData).split('id="performance"')[1].split('class="content-card"')[0];
assert(!mixedPeriodHtml.includes('YTD') && !mixedPeriodHtml.includes('Alpha') && !mixedPeriodHtml.includes('metric-strip'));
windowData.performance.windowReturns.endDate = '2026-07-01';
assert(validate(windowData, SCHEMA).some(error => error.includes('startDate')));
// Aucun lien vers l'infrastructure interne ne sort du rendu.
const internal = JSON.parse(JSON.stringify(windowData));
internal.performance = undefined;
internal.fundamentals = internal.fundamentals || {};
internal.fundamentals.sourceRefs = [{ name: 'Données', url: 'https://mcp.dailytickers.com/mcp', date: '2026-09-24' }];
const internalHtml = render(internal);
assert(!internalHtml.includes('mcp.dailytickers.com'), 'internal MCP host must never be rendered');
assert(internalHtml.includes(`https://articles.dailytickers.com/data/analyses-evidence/${internal.header.ticker}.json`), 'internal source maps to the public evidence file');
console.log('analysis render fidelity: PASS');
